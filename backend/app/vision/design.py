"""系统设计题的题面与评分维度（M13）。

与算法题不同，系统设计题**没有唯一正确答案**，所以这个模块的重点不是「答案」，
而是**评分维度**：一道 CV 系统设计题应该从哪几个方向看，每个方向希望候选人
主动提到什么。

`rubric` 里的维度是按「面试官实际会怎么听」组织的，分四类：

- **需求澄清**：有没有先问约束。跳过这一步直接给方案，是系统设计最常见的失分点；
- **整体架构**：数据怎么流、模块怎么分；
- **关键取舍**：延迟/吞吐、精度/速度、成本/可维护性——**这是分水岭**；
- **边界与故障**：异常怎么处理、长期怎么维护。

每题还带 `constraints`（题面直接给的硬约束）与 `open_questions`（题面**故意不给**、
需要候选人自己问的）。后者是设计题和普通问答最本质的区别：
**信息不全是常态，先问清再设计才是正确做法。**
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True, slots=True)
class RubricDimension:
    dimension: str
    """维度名，如「需求澄清」「关键取舍」"""
    expects: list[str]
    """希望候选人提到的要点，作为评估对照"""
    weight: str = "normal"
    """`core` 表示这一维是及格线，`bonus` 表示加分项"""


@dataclass(frozen=True, slots=True)
class DesignQuestion:
    slug: str
    title: str
    difficulty: int
    tags: list[str]
    statement: str
    """场景与要求（Markdown）"""
    constraints: list[str]
    """题面已知的硬约束"""
    open_questions: list[str]
    """题面故意不给、需要候选人主动问清的"""
    rubric: list[RubricDimension]
    followups: list[str]
    hints: list[str] = field(default_factory=list)
    """可以从哪几个角度切入，卡住时才看"""


